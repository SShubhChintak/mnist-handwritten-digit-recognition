# Create the CNN model
model = keras.Sequential(
    [

        # Input layer: 28x28 grayscale image
        keras.Input(shape=(28, 28, 1)),

        # CONVOLUTION BLOCK 1
        layers.Conv2D(
            32,
            kernel_size=(3, 3),
            padding="same",
            activation="relu"
        ),

        layers.BatchNormalization(),

        layers.Conv2D(
            32,
            kernel_size=(3, 3),
            padding="same",
            activation="relu"
        ),

        layers.BatchNormalization(),

        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.25),

        # CONVOLUTION BLOCK 2
        layers.Conv2D(
            64,
            kernel_size=(3, 3),
            padding="same",
            activation="relu"
        ),

        layers.BatchNormalization(),

        layers.Conv2D(
            64,
            kernel_size=(3, 3),
            padding="same",
            activation="relu"
        ),

        layers.BatchNormalization(),

        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.25),

        # FEATURE EXTRACTION
        layers.Flatten(),

        # FULLY CONNECTED LAYER
        layers.Dense(
            128,
            activation="relu"
        ),

        layers.BatchNormalization(),
        layers.Dropout(0.40),

        # OUTPUT LAYER: DIGITS 0 TO 9
        layers.Dense(
            10,
            activation="softmax"
        )

    ],
    name="MNIST_Improved_CNN"
)

