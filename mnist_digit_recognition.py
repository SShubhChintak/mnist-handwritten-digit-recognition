from PIL import Image

def preprocess_canvas(editor_value):

    # 1. Extract image from Gradio ImageEditor
    if isinstance(editor_value, dict):
        image = editor_value.get("composite")

        if image is None:
            image = editor_value.get("background")
    else:
        image = editor_value

    if image is None:
        raise gr.Error("Please upload or draw a digit!")

    # 2. Convert image into a NumPy array
    image_array = np.asarray(image)

    if image_array.size == 0:
        raise gr.Error("Empty image! Please upload a valid digit.")

    image_float = image_array.astype(np.float32)

    if not np.isfinite(image_float).all():
        raise gr.Error("Invalid image pixel values!")

    # 3. Standardize pixel range to 0-255
    if image_float.max() <= 1.0:
        image_float *= 255.0

    image_float = np.clip(image_float, 0, 255)

    # 4. Convert image into grayscale
    if image_float.ndim == 3:

        channels = image_float.shape[-1]

        if channels == 1:
            gray = image_float[..., 0]

        elif channels in (3, 4):

            gray = (
                0.299 * image_float[..., 0]
                + 0.587 * image_float[..., 1]
                + 0.114 * image_float[..., 2]
            )

            # Correctly handle transparency
            if channels == 4:
                alpha = image_float[..., 3] / 255.0
                gray = gray * alpha

        else:
            raise gr.Error("Unsupported image channel format!")

    elif image_float.ndim == 2:
        gray = image_float

    else:
        raise gr.Error("Invalid image format!")

    gray_image = np.clip(
        gray, 0, 255
    ).astype(np.uint8)

    # 5. Detect white-background images and invert
    border_pixels = np.concatenate([
        gray_image[0, :],
        gray_image[-1, :],
        gray_image[:, 0],
        gray_image[:, -1]
    ])

    if np.median(border_pixels) > 127:
        gray_image = 255 - gray_image

    # 6. Reject blank images
    if gray_image.max() <= 20:
        raise gr.Error("Blank image! Please draw a digit.")

    # 7. Preserve correctly formatted MNIST images
    if gray_image.shape == (28, 28):
        return gray_image.astype(np.float32) / 255.0

    # 8. Identify digit boundaries
    mask = gray_image > 20
    coordinates = np.argwhere(mask)

    if coordinates.size == 0:
        raise gr.Error("No digit detected!")

    top, left = coordinates.min(axis=0)
    bottom, right = coordinates.max(axis=0)

    # 9. Crop the digit
    cropped_digit = gray_image[
        top:bottom + 1,
        left:right + 1
    ]

    # 10. Resize while preserving proportions
    height, width = cropped_digit.shape

    scale = 20.0 / max(height, width)

    new_height = max(1, int(round(height * scale)))
    new_width = max(1, int(round(width * scale)))

    resized_digit = Image.fromarray(
        cropped_digit
    ).resize(
        (new_width, new_height),
        Image.Resampling.LANCZOS
    )

    # 11. Place digit on a 28x28 black canvas
    final_canvas = Image.new(
        "L",
        (28, 28),
        color=0
    )

    position = (
        (28 - new_width) // 2,
        (28 - new_height) // 2
    )

    final_canvas.paste(resized_digit, position)

    # 12. Normalize pixel values
    processed_image = (
        np.asarray(final_canvas, dtype=np.float32) / 255.0
    )

    return processed_image


